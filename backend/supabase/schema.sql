-- Luxor Création — Supabase schema (tables, security rules, photo storage).
-- Safe to run more than once.
--   psql "$SUPABASE_DB_URL" -f backend/supabase/schema.sql

begin;

-- ---------- tables ----------
create table if not exists public.categories (
  id          text primary key,                 -- e.g. 'canapes'
  name        text not null,
  description text not null default '',
  sort        integer not null default 0
);

create table if not exists public.colors (
  name text primary key,
  hex  text not null check (hex ~ '^#[0-9A-Fa-f]{6}$'),
  sort integer not null default 0
);

create table if not exists public.products (
  id          integer generated by default as identity primary key,
  slug        text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name        text not null check (length(name) between 1 and 120),
  category    text not null references public.categories(id) on update cascade,
  description text not null default '' check (length(description) <= 4000),
  price       integer not null default 0 check (price >= 0),       -- DH
  sku         text not null default '',
  material    text not null default '',
  dimensions  text not null default '',
  color       text not null default '',
  image       text not null default '',          -- full URL (optional)
  fallback    text not null default '',          -- file in frontend/assets/ or Storage URL
  gallery     text[] not null default '{}',
  featured    boolean not null default false,
  is_new      boolean not null default false,
  sort        integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists products_category_idx on public.products(category, sort);

-- admins = Supabase Auth users allowed to edit
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email   text not null
);

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

create or replace function public.touch_updated_at() returns trigger
language plpgsql set search_path = public as $$
begin new.updated_at = now(); return new; end $$;
drop trigger if exists products_touch on public.products;
create trigger products_touch before update on public.products for each row execute function public.touch_updated_at();

-- ---------- row level security ----------
alter table public.categories enable row level security;
alter table public.colors     enable row level security;
alter table public.products   enable row level security;
alter table public.admins     enable row level security;

-- everyone can read the catalogue
drop policy if exists "public read categories" on public.categories;
create policy "public read categories" on public.categories for select using (true);
drop policy if exists "public read colors" on public.colors;
create policy "public read colors" on public.colors for select using (true);
drop policy if exists "public read products" on public.products;
create policy "public read products" on public.products for select using (true);

-- only admins can write
drop policy if exists "admin write categories" on public.categories;
create policy "admin write categories" on public.categories for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admin write colors" on public.colors;
create policy "admin write colors" on public.colors for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admin insert products" on public.products;
create policy "admin insert products" on public.products for insert to authenticated with check (public.is_admin());
drop policy if exists "admin update products" on public.products;
create policy "admin update products" on public.products for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admin delete products" on public.products;
create policy "admin delete products" on public.products for delete to authenticated using (public.is_admin());

-- an admin can see their own admin row (used by the admin page to check access); nobody can change it via the API
drop policy if exists "admin sees self" on public.admins;
create policy "admin sees self" on public.admins for select to authenticated using (user_id = auth.uid());

grant select on public.categories, public.colors, public.products to anon, authenticated;
grant insert, update, delete on public.categories, public.colors, public.products to authenticated;
grant select on public.admins to authenticated;
revoke insert, update, delete on public.admins from anon, authenticated;

-- ---------- photo storage ----------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('products', 'products', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "public read product photos" on storage.objects;
create policy "public read product photos" on storage.objects for select using (bucket_id = 'products');
drop policy if exists "admin upload product photos" on storage.objects;
create policy "admin upload product photos" on storage.objects for insert to authenticated with check (bucket_id = 'products' and public.is_admin());
drop policy if exists "admin update product photos" on storage.objects;
create policy "admin update product photos" on storage.objects for update to authenticated using (bucket_id = 'products' and public.is_admin());
drop policy if exists "admin delete product photos" on storage.objects;
create policy "admin delete product photos" on storage.objects for delete to authenticated using (bucket_id = 'products' and public.is_admin());

commit;
